class TemplateRenderer:
    def __init__(self):
        self.env = Environment(loader=BaseLoader())
        self.whatsapp_tmpl = self.env.from_string(WHATSAPP_TEXT_TEMPLATE)
        self.html_tmpl = self.env.from_string(HTML_DISPATCH_SLIP_TEMPLATE)

    def render_whatsapp_summary(self, context: Dict[str, Any]) -> str:
        return self.whatsapp_tmpl.render(**context)

    def render_html_slip(self, context: Dict[str, Any]) -> str:
        return self.html_tmpl.render(**context)


